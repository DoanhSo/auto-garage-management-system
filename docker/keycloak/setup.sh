#!/bin/bash
set -euo pipefail
if [[ -z "${GARAGE_ADMIN_PASSWORD:-}" ]]; then
    echo 'Automatic garage administrator setup is disabled; existing realm users are preserved.'
    exit 0
fi
[[ "${GARAGE_ADMIN_USERNAME:-}" =~ ^[A-Za-z0-9._-]{3,100}$ ]] || { echo 'Invalid garage administrator username' >&2; exit 1; }
[[ "$GARAGE_ADMIN_PASSWORD" =~ ^[A-Za-z0-9_-]{24,72}$ ]] || { echo 'Garage password must be generated by the Docker launcher' >&2; exit 1; }
[[ "$FRONTEND_PUBLIC_URL" =~ ^https?://[A-Za-z0-9._:-]+$ ]] || { echo 'Invalid frontend URL' >&2; exit 1; }
umask 077
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
kc() { /opt/keycloak/bin/kcadm.sh "$@" --config "$work/admin.config"; }
kc config credentials --server http://keycloak:8080 --realm master \
    --user "$KEYCLOAK_ADMIN_USERNAME" --password "$KEYCLOAK_ADMIN_PASSWORD" >/dev/null
realm=autogarage-realm
client=$(kc get clients -r "$realm" -q clientId=autogarage-frontend --fields id --format csv --noquotes | tail -n 1 | tr -d '\r')
[[ "$client" =~ ^[a-f0-9-]{36}$ ]] || { echo 'Frontend client is missing' >&2; exit 1; }
printf '{"redirectUris":["%s/login","http://localhost:5173/*","http://127.0.0.1:5173/*"],"webOrigins":["%s","http://localhost:5173","http://127.0.0.1:5173"]}' \
    "$FRONTEND_PUBLIC_URL" "$FRONTEND_PUBLIC_URL" > "$work/client.json"
kc update "clients/$client" -r "$realm" -f "$work/client.json"
kc update users/profile -r "$realm" -f /opt/autogarage/user-profile.json
if ! kc get "clients/$client/protocol-mappers/models" -r "$realm" --fields name --format csv --noquotes | grep -Fxq 'autogarage-auth-version'; then
    kc create "clients/$client/protocol-mappers/models" -r "$realm" -f /opt/autogarage/auth-version-mapper.json >/dev/null
fi
existing=$(kc get users -r "$realm" -q "username=$GARAGE_ADMIN_USERNAME" -q exact=true --fields id --format csv --noquotes | tr -d '\r' | sed '/^id$/d')
if [[ -n "$existing" ]]; then
    [[ -f /run/autogarage/identity-id && "$existing" == "$(cat /run/autogarage/identity-id)" ]] || { echo 'Existing administrator identity differs; refusing to overwrite it.' >&2; exit 1; }
    if [[ -f /run/autogarage/ready ]]; then
        echo 'Existing garage administrator preserved; password and auth_version were not reset.'
        exit 0
    fi
    GARAGE_ADMIN_ID="$existing"
else
    printf '{"username":"%s","enabled":true,"emailVerified":true,"email":"garage.admin@example.test","firstName":"Garage","lastName":"Administrator","attributes":{"auth_version":["0"]},"credentials":[{"type":"password","value":"%s","temporary":false}]}' \
        "$GARAGE_ADMIN_USERNAME" "$GARAGE_ADMIN_PASSWORD" > "$work/user.json"
    GARAGE_ADMIN_ID=$(kc create users -r "$realm" -f "$work/user.json" -i | tr -d '\r')
    [[ "$GARAGE_ADMIN_ID" =~ ^[a-f0-9-]{36}$ ]] || { echo 'Keycloak did not return a valid new user ID' >&2; exit 1; }
    printf '%s\n' "$GARAGE_ADMIN_ID" > /run/autogarage/identity-id
    chmod 644 /run/autogarage/identity-id
fi
roles=$(kc get "users/$GARAGE_ADMIN_ID/role-mappings/realm" -r "$realm" --fields name --format csv --noquotes | tr -d '\r' | sed '/^name$/d')
while IFS= read -r role; do
    case "$role" in
        CUSTOMER|RECEPTIONIST|WAREHOUSE_STAFF|TECHNICIAN|default-roles-autogarage-realm)
            kc remove-roles -r "$realm" --uid "$GARAGE_ADMIN_ID" --rolename "$role" ;;
    esac
done <<< "$roles"
kc add-roles -r "$realm" --uid "$GARAGE_ADMIN_ID" --rolename ADMIN
touch /run/autogarage/ready
chmod 644 /run/autogarage/ready
echo 'Garage administrator created with the configured identity and ADMIN role.'
