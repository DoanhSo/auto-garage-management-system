-- MySQL 8.4 / InnoDB. Times are UTC; monetary values use DECIMAL.
-- Source report omits the full column dictionary. See docs/DATABASE.md for decisions.
CREATE TABLE users (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    username VARCHAR(100) NOT NULL,
    email VARCHAR(254) NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    role VARCHAR(30) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    last_login_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN','RECEPTIONIST','WAREHOUSE_STAFF','TECHNICIAN','CUSTOMER'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE customers (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    user_id BIGINT NULL,
    customer_code VARCHAR(30) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    customer_type VARCHAR(20) NOT NULL DEFAULT 'INDIVIDUAL',
    phone VARCHAR(30) NOT NULL,
    email VARCHAR(254) NULL,
    address VARCHAR(500) NULL,
    company_name VARCHAR(255) NULL,
    tax_code VARCHAR(30) NULL,
    credit_limit DECIMAL(18,2) NOT NULL DEFAULT 0,
    payment_term_days INT NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_customers_code UNIQUE (customer_code),
    CONSTRAINT uq_customers_user UNIQUE (user_id),
    CONSTRAINT fk_customers_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT ck_customers_type CHECK (customer_type IN ('INDIVIDUAL','BUSINESS')),
    CONSTRAINT ck_customers_credit CHECK (credit_limit >= 0 AND payment_term_days >= 0),
    INDEX ix_customers_phone (phone)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE vehicles (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    license_plate VARCHAR(20) NOT NULL,
    vin VARCHAR(17) NULL,
    engine_number VARCHAR(50) NULL,
    brand VARCHAR(80) NOT NULL,
    model VARCHAR(80) NOT NULL,
    manufacture_year SMALLINT NULL,
    color VARCHAR(50) NULL,
    fuel_type VARCHAR(30) NULL,
    odometer INT NOT NULL DEFAULT 0,
    inspection_due_date DATE NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_vehicles_plate UNIQUE (license_plate),
    CONSTRAINT uq_vehicles_vin UNIQUE (vin),
    CONSTRAINT fk_vehicles_customer FOREIGN KEY (customer_id) REFERENCES customers(id),
    CONSTRAINT ck_vehicles_odometer CHECK (odometer >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE services (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    service_code VARCHAR(30) NOT NULL,
    service_name VARCHAR(150) NOT NULL,
    service_type VARCHAR(20) NOT NULL DEFAULT 'SINGLE',
    description TEXT NULL,
    unit VARCHAR(30) NOT NULL DEFAULT 'job',
    unit_price DECIMAL(18,2) NOT NULL DEFAULT 0,
    standard_minutes INT NOT NULL,
    required_bay_type VARCHAR(30) NULL,
    required_skills_json JSON NULL,
    interval_km INT NULL,
    interval_months INT NULL,
    warranty_days INT NOT NULL DEFAULT 0,
    warranty_km INT NOT NULL DEFAULT 0,
    warranty_terms TEXT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_services_code UNIQUE (service_code),
    CONSTRAINT ck_services_type CHECK (service_type IN ('SINGLE','PACKAGE')),
    CONSTRAINT ck_services_values CHECK (unit_price >= 0 AND standard_minutes > 0 AND warranty_days >= 0 AND warranty_km >= 0),
    CONSTRAINT ck_services_intervals CHECK ((interval_km IS NULL OR interval_km > 0) AND (interval_months IS NULL OR interval_months > 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE employees (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    employee_code VARCHAR(30) NOT NULL,
    skills_json JSON NULL,
    can_qc BOOLEAN NOT NULL DEFAULT FALSE,
    hourly_cost DECIMAL(18,2) NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_employees_code UNIQUE (employee_code),
    CONSTRAINT uq_employees_user UNIQUE (user_id),
