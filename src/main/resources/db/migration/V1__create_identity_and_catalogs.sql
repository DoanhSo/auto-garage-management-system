CREATE TABLE parts (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    sku VARCHAR(50) NOT NULL,
    part_name VARCHAR(150) NOT NULL,
    unit VARCHAR(30) NOT NULL,
    description TEXT NULL,
    preferred_supplier_id BIGINT NULL,
    purchase_price DECIMAL(18,2) NOT NULL DEFAULT 0,
    selling_price DECIMAL(18,2) NOT NULL DEFAULT 0,
    stock_quantity DECIMAL(14,3) NOT NULL DEFAULT 0,
    reserved_quantity DECIMAL(14,3) NOT NULL DEFAULT 0,
    reorder_level DECIMAL(14,3) NOT NULL DEFAULT 0,
    warranty_days INT NOT NULL DEFAULT 0,
    warranty_km INT NOT NULL DEFAULT 0,
    warranty_terms TEXT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_parts_sku UNIQUE (sku),
    CONSTRAINT fk_parts_supplier FOREIGN KEY (preferred_supplier_id) REFERENCES suppliers(id),
    CONSTRAINT ck_parts_stock CHECK (stock_quantity >= 0 AND reserved_quantity >= 0 AND reserved_quantity <= stock_quantity),
    CONSTRAINT ck_parts_prices CHECK (purchase_price >= 0 AND selling_price >= 0 AND reorder_level >= 0),
    CONSTRAINT ck_parts_warranty CHECK (warranty_days >= 0 AND warranty_km >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE notifications (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    user_id BIGINT NULL,
    customer_id BIGINT NULL,
    recipient_key VARCHAR(100) COLLATE utf8mb4_bin NOT NULL,
    destination VARCHAR(254) NOT NULL,
    event_key VARCHAR(150) COLLATE utf8mb4_bin NOT NULL,
    channel VARCHAR(10) NOT NULL,
    subject VARCHAR(255) NULL,
    payload_json JSON NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempt_count INT NOT NULL DEFAULT 0,
    next_attempt_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    locked_until DATETIME(6) NULL,
    locked_by VARCHAR(100) NULL,
    last_error TEXT NULL,
    provider_reference VARCHAR(150) NULL,
    sent_at DATETIME(6) NULL,
    read_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_notifications_customer FOREIGN KEY (customer_id) REFERENCES customers(id),
    CONSTRAINT uq_notice_event_channel UNIQUE (event_key,channel,recipient_key),
    CONSTRAINT ck_notifications_recipient CHECK (user_id IS NOT NULL OR customer_id IS NOT NULL),
    CONSTRAINT ck_notifications_channel CHECK (channel IN ('WEB','EMAIL','SMS')),
    CONSTRAINT ck_notifications_status CHECK (status IN ('PENDING','PROCESSING','SENT','FAILED')),
    CONSTRAINT ck_notifications_attempt CHECK (attempt_count >= 0),
    INDEX ix_notifications_worker (status,next_attempt_at,locked_until)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE audit_events (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    actor_user_id BIGINT NULL,
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(80) NOT NULL,
    entity_id BIGINT NULL,
    request_key VARCHAR(100) COLLATE utf8mb4_bin NULL,
    request_hash CHAR(64) COLLATE utf8mb4_bin NULL,
    result_json JSON NULL,
    before_json JSON NULL,
    after_json JSON NULL,
    ip_address VARCHAR(45) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT fk_audit_actor FOREIGN KEY (actor_user_id) REFERENCES users(id),
    CONSTRAINT uq_audit_request UNIQUE (request_key),
    CONSTRAINT ck_audit_request CHECK ((request_key IS NULL AND request_hash IS NULL) OR (request_key IS NOT NULL AND request_hash IS NOT NULL)),
    INDEX ix_audit_entity (entity_type,entity_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
