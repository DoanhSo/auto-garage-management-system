    CONSTRAINT ck_employees_cost CHECK (hourly_cost >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE employee_shifts (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    employee_id BIGINT NOT NULL,
    starts_at DATETIME(6) NOT NULL,
    ends_at DATETIME(6) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    notes TEXT NULL,
    created_by BIGINT NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_shifts_employee FOREIGN KEY (employee_id) REFERENCES employees(id),
    CONSTRAINT fk_shifts_creator FOREIGN KEY (created_by) REFERENCES users(id),
    CONSTRAINT ck_shifts_interval CHECK (ends_at > starts_at),
    CONSTRAINT ck_shifts_status CHECK (status IN ('ACTIVE','CANCELLED')),
    INDEX ix_shifts_employee_time (employee_id,status,starts_at,ends_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

