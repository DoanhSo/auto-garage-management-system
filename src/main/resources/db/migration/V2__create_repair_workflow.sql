CREATE TABLE repair_orders (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    order_code VARCHAR(30) NOT NULL,
    booking_id BIGINT NULL,
    customer_id BIGINT NOT NULL,
    vehicle_id BIGINT NOT NULL,
    order_type VARCHAR(20) NOT NULL DEFAULT 'NORMAL',
    status VARCHAR(30) NOT NULL DEFAULT 'NEW',
    odometer_in INT NOT NULL,
    odometer_out INT NULL,
    fuel_level_percent DECIMAL(5,2) NULL,
    customer_complaint TEXT NULL,
    diagnosis TEXT NULL,
    received_by BIGINT NOT NULL,
    received_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    latest_qc_check_id BIGINT NULL,
    handed_over_by BIGINT NULL,
    handed_over_at DATETIME(6) NULL,
    closed_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_orders_code UNIQUE (order_code),
    CONSTRAINT uq_orders_booking UNIQUE (booking_id),
    CONSTRAINT fk_orders_booking FOREIGN KEY (booking_id) REFERENCES bookings(id),
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customers(id),
    CONSTRAINT fk_orders_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles(id),
    CONSTRAINT fk_orders_receiver FOREIGN KEY (received_by) REFERENCES users(id),
    CONSTRAINT fk_orders_handover FOREIGN KEY (handed_over_by) REFERENCES users(id),
    CONSTRAINT ck_orders_type CHECK (order_type IN ('NORMAL','WARRANTY')),
    CONSTRAINT ck_orders_status CHECK (status IN ('NEW','DIAGNOSING','WAITING_APPROVAL','APPROVED','IN_PROGRESS','WAITING_PARTS','WAITING_QC','QC_FAILED','COMPLETED','INVOICED','CLOSED','CANCELLED')),
    CONSTRAINT ck_orders_odometer CHECK (odometer_in >= 0 AND (odometer_out IS NULL OR odometer_out >= odometer_in)),
    CONSTRAINT ck_orders_fuel CHECK (fuel_level_percent IS NULL OR fuel_level_percent BETWEEN 0 AND 100),
    INDEX ix_orders_vehicle_history (vehicle_id,received_at),
    INDEX ix_orders_status (status,received_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE bay_reservations (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    bay_id BIGINT NOT NULL,
    booking_id BIGINT NULL,
    repair_order_id BIGINT NULL,
    reservation_type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'HELD',
    starts_at DATETIME(6) NOT NULL,
    ends_at DATETIME(6) NOT NULL,
    expires_at DATETIME(6) NULL,
    released_at DATETIME(6) NULL,
    notes TEXT NULL,
    created_by BIGINT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_reservations_bay FOREIGN KEY (bay_id) REFERENCES service_bays(id),
    CONSTRAINT fk_reservations_booking FOREIGN KEY (booking_id) REFERENCES bookings(id),
    CONSTRAINT fk_reservations_order FOREIGN KEY (repair_order_id) REFERENCES repair_orders(id),
    CONSTRAINT fk_reservations_creator FOREIGN KEY (created_by) REFERENCES users(id),
    CONSTRAINT ck_reservations_interval CHECK (ends_at > starts_at),
    CONSTRAINT ck_reservations_status CHECK (status IN ('HELD','IN_USE','RELEASED','EXPIRED','CANCELLED')),
    CONSTRAINT ck_reservations_source CHECK (
        (reservation_type = 'BOOKING' AND booking_id IS NOT NULL AND repair_order_id IS NULL) OR
        (reservation_type = 'REPAIR' AND repair_order_id IS NOT NULL AND booking_id IS NULL) OR
        (reservation_type = 'MAINTENANCE' AND booking_id IS NULL AND repair_order_id IS NULL)),
    INDEX ix_reservations_overlap (bay_id,status,starts_at,ends_at),
    INDEX ix_reservations_expiry (status,expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE estimates (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    estimate_code VARCHAR(30) NOT NULL,
    repair_order_id BIGINT NOT NULL,
    version_no INT NOT NULL,
    estimate_kind VARCHAR(20) NOT NULL DEFAULT 'INITIAL',
    parent_estimate_id BIGINT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    subtotal DECIMAL(18,2) NOT NULL DEFAULT 0,
    discount_amount DECIMAL(18,2) NOT NULL DEFAULT 0,
    tax_amount DECIMAL(18,2) NOT NULL DEFAULT 0,
    total_amount DECIMAL(18,2) NOT NULL DEFAULT 0,
    notes TEXT NULL,
    created_by BIGINT NOT NULL,
    sent_at DATETIME(6) NULL,
    valid_until DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_estimates_code UNIQUE (estimate_code),
    CONSTRAINT uq_estimates_version UNIQUE (repair_order_id,version_no),
    CONSTRAINT uq_estimates_id_order UNIQUE (id,repair_order_id),
    CONSTRAINT fk_estimates_order FOREIGN KEY (repair_order_id) REFERENCES repair_orders(id),
    CONSTRAINT fk_estimates_parent FOREIGN KEY (parent_estimate_id,repair_order_id) REFERENCES estimates(id,repair_order_id),
    CONSTRAINT fk_estimates_creator FOREIGN KEY (created_by) REFERENCES users(id),
    CONSTRAINT ck_estimates_kind CHECK ((estimate_kind = 'INITIAL' AND parent_estimate_id IS NULL) OR (estimate_kind = 'SUPPLEMENTAL' AND parent_estimate_id IS NOT NULL)),
    CONSTRAINT ck_estimates_status CHECK (status IN ('DRAFT','SENT','APPROVED','PARTIALLY_APPROVED','REJECTED','EXPIRED','CANCELLED')),
    CONSTRAINT ck_estimates_version CHECK (version_no > 0),
    CONSTRAINT ck_estimates_amount CHECK (subtotal >= 0 AND discount_amount >= 0 AND discount_amount <= subtotal AND tax_amount >= 0 AND total_amount = subtotal - discount_amount + tax_amount)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE estimate_items (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    estimate_id BIGINT NOT NULL,
    line_no INT NOT NULL,
    item_type VARCHAR(10) NOT NULL,
    service_id BIGINT NULL,
    part_id BIGINT NULL,
    item_name VARCHAR(150) NOT NULL,
    unit VARCHAR(30) NOT NULL,
    quantity DECIMAL(14,3) NOT NULL,
    unit_price DECIMAL(18,2) NOT NULL,
    unit_cost DECIMAL(18,2) NOT NULL DEFAULT 0,
    discount_amount DECIMAL(18,2) NOT NULL DEFAULT 0,
    tax_amount DECIMAL(18,2) NOT NULL DEFAULT 0,
    line_total DECIMAL(18,2) NOT NULL,
    approval_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    approved_by BIGINT NULL,
    decided_at DATETIME(6) NULL,
    decision_note TEXT NULL,
    reserved_quantity DECIMAL(14,3) NOT NULL DEFAULT 0,
    warranty_days INT NOT NULL DEFAULT 0,
    warranty_km INT NOT NULL DEFAULT 0,
    warranty_terms TEXT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_estimate_items_line UNIQUE (estimate_id,line_no),
    CONSTRAINT fk_estimate_items_estimate FOREIGN KEY (estimate_id) REFERENCES estimates(id),
    CONSTRAINT fk_estimate_items_service FOREIGN KEY (service_id) REFERENCES services(id),
    CONSTRAINT fk_estimate_items_part FOREIGN KEY (part_id) REFERENCES parts(id),
    CONSTRAINT fk_estimate_items_approver FOREIGN KEY (approved_by) REFERENCES users(id),
    CONSTRAINT ck_estimate_items_source CHECK ((item_type = 'SERVICE' AND service_id IS NOT NULL AND part_id IS NULL) OR (item_type = 'PART' AND part_id IS NOT NULL AND service_id IS NULL)),
    CONSTRAINT ck_estimate_items_values CHECK (line_no > 0 AND quantity > 0 AND unit_price >= 0 AND unit_cost >= 0 AND discount_amount >= 0 AND discount_amount <= ROUND(quantity * unit_price,2) AND tax_amount >= 0 AND line_total = ROUND(quantity * unit_price,2) - discount_amount + tax_amount),
    CONSTRAINT ck_estimate_items_approval CHECK (approval_status IN ('PENDING','APPROVED','REJECTED')),
    CONSTRAINT ck_estimate_items_reserved CHECK (reserved_quantity >= 0 AND reserved_quantity <= quantity AND (reserved_quantity = 0 OR (item_type = 'PART' AND approval_status = 'APPROVED'))),
    CONSTRAINT ck_estimate_items_warranty CHECK (warranty_days >= 0 AND warranty_km >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE repair_tasks (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    repair_order_id BIGINT NOT NULL,
    estimate_item_id BIGINT NULL,
    service_id BIGINT NULL,
    task_type VARCHAR(20) NOT NULL DEFAULT 'REPAIR',
    task_name VARCHAR(150) NOT NULL,
    description TEXT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    quantity DECIMAL(14,3) NOT NULL DEFAULT 1,
    unit_price DECIMAL(18,2) NOT NULL DEFAULT 0,
    started_at DATETIME(6) NULL,
    completed_at DATETIME(6) NULL,
    completion_note TEXT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_tasks_estimate_item UNIQUE (estimate_item_id),
    CONSTRAINT fk_tasks_order FOREIGN KEY (repair_order_id) REFERENCES repair_orders(id),
    CONSTRAINT fk_tasks_estimate_item FOREIGN KEY (estimate_item_id) REFERENCES estimate_items(id),
    CONSTRAINT fk_tasks_service FOREIGN KEY (service_id) REFERENCES services(id),
    CONSTRAINT ck_tasks_type CHECK ((task_type = 'REPAIR' AND estimate_item_id IS NOT NULL AND service_id IS NOT NULL) OR (task_type = 'DIAGNOSIS' AND estimate_item_id IS NULL)),
    CONSTRAINT ck_tasks_status CHECK (status IN ('PENDING','ASSIGNED','IN_PROGRESS','PAUSED','COMPLETED','REWORK','CANCELLED')),
    CONSTRAINT ck_tasks_values CHECK (quantity > 0 AND unit_price >= 0),
    INDEX ix_tasks_order_status (repair_order_id,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE task_assignments (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    task_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL,
    assignment_role VARCHAR(20) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    starts_at DATETIME(6) NOT NULL,
    ends_at DATETIME(6) NOT NULL,
    assigned_by BIGINT NOT NULL,
    assigned_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    released_at DATETIME(6) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    active_main_task_id BIGINT GENERATED ALWAYS AS (CASE WHEN assignment_role = 'MAIN' AND is_active = TRUE THEN task_id ELSE NULL END) STORED,
    CONSTRAINT uq_assignments_active_main UNIQUE (active_main_task_id),
    CONSTRAINT uq_assignments_id_employee UNIQUE (id,employee_id),
    CONSTRAINT fk_assignments_task FOREIGN KEY (task_id) REFERENCES repair_tasks(id),
    CONSTRAINT fk_assignments_employee FOREIGN KEY (employee_id) REFERENCES employees(id),
    CONSTRAINT fk_assignments_assigner FOREIGN KEY (assigned_by) REFERENCES users(id),
    CONSTRAINT ck_assignments_role CHECK (assignment_role IN ('MAIN','ASSISTANT','QC')),
    CONSTRAINT ck_assignments_interval CHECK (ends_at > starts_at),
    INDEX ix_assignments_employee_time (employee_id,is_active,starts_at,ends_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE labor_sessions (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    assignment_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL,
    starts_at DATETIME(6) NOT NULL,
    ends_at DATETIME(6) NULL,
    stop_reason VARCHAR(20) NULL,
    hourly_cost_snapshot DECIMAL(18,2) NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    active_employee_id BIGINT GENERATED ALWAYS AS (CASE WHEN ends_at IS NULL THEN employee_id ELSE NULL END) STORED,
    CONSTRAINT uq_labor_active_employee UNIQUE (active_employee_id),
    CONSTRAINT fk_labor_assignment_employee FOREIGN KEY (assignment_id,employee_id) REFERENCES task_assignments(id,employee_id),
    CONSTRAINT ck_labor_interval CHECK (ends_at IS NULL OR ends_at > starts_at),
    CONSTRAINT ck_labor_stop CHECK ((ends_at IS NULL AND stop_reason IS NULL) OR (ends_at IS NOT NULL AND stop_reason IS NOT NULL AND stop_reason IN ('PAUSE','COMPLETE','CANCEL'))),
    CONSTRAINT ck_labor_cost CHECK (hourly_cost_snapshot >= 0),
    INDEX ix_labor_assignment_time (assignment_id,starts_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE vehicle_checks (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    repair_order_id BIGINT NOT NULL,
    check_type VARCHAR(20) NOT NULL,
    attempt_no INT NOT NULL DEFAULT 1,
    result VARCHAR(20) NOT NULL,
    checklist_json JSON NOT NULL,
    schema_version INT NOT NULL DEFAULT 1,
    odometer INT NULL,
    notes TEXT NULL,
    checked_by BIGINT NOT NULL,
    checked_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT uq_checks_attempt UNIQUE (repair_order_id,check_type,attempt_no),
    CONSTRAINT uq_checks_id_order UNIQUE (id,repair_order_id),
    CONSTRAINT fk_checks_order FOREIGN KEY (repair_order_id) REFERENCES repair_orders(id),
    CONSTRAINT fk_checks_checker FOREIGN KEY (checked_by) REFERENCES users(id),
    CONSTRAINT ck_checks_type CHECK (check_type IN ('CHECK_IN','QC','HANDOVER')),
    CONSTRAINT ck_checks_result CHECK ((check_type = 'QC' AND result IN ('PASSED','FAILED')) OR (check_type IN ('CHECK_IN','HANDOVER') AND result = 'RECORDED')),
    CONSTRAINT ck_checks_values CHECK (attempt_no > 0 AND schema_version > 0 AND (odometer IS NULL OR odometer >= 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE attachments (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    repair_order_id BIGINT NULL,
    vehicle_check_id BIGINT NULL,
    warranty_claim_id BIGINT NULL,
    storage_key VARCHAR(500) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    size_bytes BIGINT NOT NULL,
    sha256 CHAR(64) NULL,
    category VARCHAR(30) NOT NULL,
    uploaded_by BIGINT NOT NULL,
    uploaded_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT uq_attachments_storage UNIQUE (storage_key),
    CONSTRAINT fk_attachments_order FOREIGN KEY (repair_order_id) REFERENCES repair_orders(id),
    CONSTRAINT fk_attachments_check_order FOREIGN KEY (vehicle_check_id,repair_order_id) REFERENCES vehicle_checks(id,repair_order_id),
    CONSTRAINT fk_attachments_uploader FOREIGN KEY (uploaded_by) REFERENCES users(id),
    CONSTRAINT ck_attachments_target CHECK (
        (repair_order_id IS NOT NULL AND warranty_claim_id IS NULL) OR
        (repair_order_id IS NULL AND warranty_claim_id IS NOT NULL AND vehicle_check_id IS NULL AND category = 'WARRANTY')),
    CONSTRAINT ck_attachments_check_target CHECK (vehicle_check_id IS NULL OR repair_order_id IS NOT NULL),
    CONSTRAINT ck_attachments_size CHECK (size_bytes > 0),
    CONSTRAINT ck_attachments_category CHECK (category IN ('CHECK_IN','DIAGNOSIS','QC','HANDOVER','WARRANTY'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
