package com.Group13_65CNTT.AutoGarage.reception.service.impl;

import com.Group13_65CNTT.AutoGarage.common.config.WorkshopProperties;
import com.Group13_65CNTT.AutoGarage.common.enums.ResponseCode;
import com.Group13_65CNTT.AutoGarage.common.exception.BusinessException;
import com.Group13_65CNTT.AutoGarage.common.util.SafeFailureLog;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Component;
import org.springframework.transaction.support.TransactionSynchronization;
import org.springframework.transaction.support.TransactionSynchronizationManager;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.NoSuchFileException;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;

/** Private storage; keys are generated by the server and never accepted as download paths. */
@Component
@RequiredArgsConstructor
@Slf4j
public class AttachmentStorage {
    private final WorkshopProperties properties;

    public void store(String key, byte[] content) {
        Path path = resolve(key);
        boolean created = false;
        try {
            Files.createDirectories(path.getParent());
            Files.createFile(path);
            created = true;
            Files.write(path, content, StandardOpenOption.WRITE);
        } catch (IOException failure) {
            if (created) remove(key);
            throw new BusinessException(ResponseCode.SERVICE_UNAVAILABLE, failure);
        }
        if (TransactionSynchronizationManager.isSynchronizationActive()) {
            TransactionSynchronizationManager.registerSynchronization(new TransactionSynchronization() {
                @Override
                public void afterCompletion(int status) {
                    if (status != STATUS_COMMITTED) remove(key);
                }
            });
        }
    }

    public byte[] read(String key) {
        try {
            return Files.readAllBytes(resolve(key));
        } catch (NoSuchFileException missing) {
            throw new BusinessException(ResponseCode.RESOURCE_NOT_FOUND, missing);
        } catch (IOException failure) {
            throw new BusinessException(ResponseCode.SERVICE_UNAVAILABLE, failure);
        }
    }

    public void remove(String key) {
        try {
            Files.deleteIfExists(resolve(key));
        } catch (IOException failure) {
            // Cleanup failures must remain visible without exposing filesystem details.
            SafeFailureLog.error(log, "Attachment cleanup failed", failure);
        }
    }

    private Path resolve(String key) {
        Path root = properties.getAttachmentDirectory().toAbsolutePath().normalize();
        Path path = root.resolve(key).normalize();
        if (!path.startsWith(root) || path.equals(root)) {
            throw new BusinessException(ResponseCode.BAD_REQUEST);
        }
        return path;
    }
}
